/// Centralized icon size tokens for AI Hustle Co-Pilot design system.
library;

/// Application icon size tokens.
abstract final class AppIconSizes {
  /// 12dp — Micro icon size (indicators, micro inline badges).
  static const double xs = 12.0;

  /// 16dp — Small icon size (inline text icons, metadata chips).
  static const double sm = 16.0;

  /// 20dp — Medium icon size (list item secondary actions, input icons).
  static const double md = 20.0;

  /// 24dp — Standard icon size (app bars, buttons, tab bars).
  static const double lg = 24.0;

  /// 32dp — Large icon size (card headers, modal banners).
  static const double xl = 32.0;

  /// 40dp — Extra-large icon size (empty state illustrations, feature badges).
  static const double xxl = 40.0;

  /// 48dp — Massive icon size (hero section visual accents).
  static const double massive = 48.0;
}
